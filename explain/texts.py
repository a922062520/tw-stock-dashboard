def horizon_reason_text(kind: str, annual_vol: float, trend_strength: float | None, risk_lvl: str, direction: str | None) -> str:
    if kind == "insufficient":
        return "所選區間不足 60 個交易日，季線尚未成形，建議拉長日期區間（至少 3 個月以上）再參考趨勢判斷。"
