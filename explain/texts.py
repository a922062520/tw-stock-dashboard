    if kind == "sideways":
        return f"月線與季線乖離僅 {trend_strength*100:.1f}%，趨勢不明顯、呈現盤整，較適合短線操作，暫不適合長期持有。"
    if kind == "trend":
        return (
            f"年化波動度為 {annual_vol*100:.1f}%（{risk_lvl}），且呈現{direction}排列"
            f"（乖離 {trend_strength*100:.1f}%），趨勢相對明確，較適合中長期布局。"
        )
    return ""


